#!/usr/bin/env python3
"""Build public food catalog from committed USDA excerpts and explicit recipe assumptions.
No connection to Auth, user journals, or the database. Run from the repository root.
"""
import csv,json,pathlib
ROOT=pathlib.Path(__file__).resolve().parents[1]
rows=list(csv.DictReader((ROOT/'nutrition/foods.tsv').open(),delimiter='\t'))
refs=json.loads((ROOT/'nutrition/usda-selected.json').read_text())
recipes=json.loads((ROOT/'nutrition/recipes.json').read_text())
KEYS=['kcal','protein','carb','fat','fiber','sugar']
def nutrition(ref,g):return {k:None if ref['per100g'][k] is None else round(ref['per100g'][k]*g/100,2) for k in KEYS}
foods=[]
for r in rows:
 ref=refs[r['fdcId']];base=float(r['base']);g=float(r['grams'])
 foods.append(dict(id=r['id'],name=r['name'],category=r['category'],emoji=r['emoji'],base=base,unit=r['unit'],**nutrition(ref,g),note=r['note'],aliases=r['aliases'].split('|'),source='مرجع USDA؛ نمونه عمومی',provenance=dict(kind='usda',fdcId=int(r['fdcId']),description=ref['description'],retrieved='2026-10-18',gramsPerBase=g)))
for r in recipes:
 assert r['yieldGrams']>0
 values={}
 for k in KEYS:
  terms=[refs[str(i['fdcId'])]['per100g'][k] for i in r['ingredients']]
  values[k]=None if any(v is None for v in terms) else round(sum(v*i['grams']/100 for v,i in zip(terms,r['ingredients']))*100/r['yieldGrams'],2)
 foods.append(dict(id=r['id'],name=r['name'],category=r['category'],emoji=r['emoji'],base=100,unit='گرم',**values,note=r['note'],aliases=r['aliases'],source='برآورد دستور نمونه؛ متغیر با پخت',provenance=dict(kind='recipe',yieldGrams=r['yieldGrams'],ingredients=r['ingredients'],retrieved='2026-10-18')))
assert len(set(f['id'] for f in foods))==len(foods)
for f in foods:
 assert f['kcal'] is not None and all(f[k] is None or f[k]>=0 for k in KEYS)
(ROOT/'docs/assets/reference-foods.js').write_text('// Generated by scripts/build-foods.py. USDA SR Legacy and explicitly modeled recipes.\nconst REFERENCE_FOODS='+json.dumps(foods,ensure_ascii=False,separators=(',',':'))+';\n')
print(f'{len(rows)} reference foods + {len(recipes)} modeled recipes = {len(foods)} sourced entries')
